const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('../.tools/ui-check/node_modules/playwright');

const root = path.join(__dirname, '..');
const output = path.join(root, 'docs/screenshots');
const password = fs.readFileSync(path.join(root, 'backend/.env'), 'utf8').match(/^DEMO_PASSWORD=(.+)$/m)[1].trim();
const base = 'http://127.0.0.1:8000/api/v1/';

(async () => {
  fs.mkdirSync(output, { recursive: true });
  const loginResponse = await fetch(base + 'auth/login/', {method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify({username: 'admin', password})});
  assert.equal(loginResponse.status, 200);
  const token = (await loginResponse.json()).access;
  const headers = {Authorization: 'Bearer ' + token, 'Content-Type': 'application/json'};
  const original = (await (await fetch(base + 'rooms/?search=101', {headers})).json()).results[0];
  const guest = (await (await fetch(base + 'customers/?search=0900000001', {headers})).json()).results[0];
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  const errors = [];
  let page;
  let createdBooking;
  let passed = false;
  try {
    page = await browser.newPage({viewport: {width: 1440, height: 1000}});
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:4173', {waitUntil: 'networkidle'});
    const placeholder = page.locator('flt-semantics-placeholder');
    await placeholder.waitFor();
    await placeholder.evaluate(element => element.click());
    await page.getByRole('button', {name: 'Đăng nhập', exact: true}).waitFor();
    await page.screenshot({path: path.join(output, 'login-desktop.png')});
    await page.setViewportSize({width: 390, height: 844});
    await page.screenshot({path: path.join(output, 'login-mobile.png')});
    await page.getByLabel('Tài khoản', {exact: true}).click();
    await page.getByLabel('Tài khoản', {exact: true}).pressSequentially('admin', {delay: 10});
    await page.getByLabel('Mật khẩu', {exact: true}).click();
    await page.getByLabel('Mật khẩu', {exact: true}).pressSequentially(password, {delay: 10});
    await page.getByLabel('Mật khẩu', {exact: true}).press('Tab');
    await page.waitForTimeout(150);
    await page.getByRole('button', {name: 'Đăng nhập', exact: true}).click();
    await page.getByText('Phòng sẵn sàng', {exact: true}).waitFor();
    await page.screenshot({path: path.join(output, 'dashboard-mobile.png')});
    await page.setViewportSize({width: 1440, height: 1000});
    await page.screenshot({path: path.join(output, 'dashboard-desktop.png')});
    await page.setViewportSize({width: 390, height: 844});
    await page.getByRole('tab', {name: 'Phòng', exact: true}).click();
    await page.getByRole('button', {name: /^101/}).waitFor();
    await page.mouse.move(1, 1);
    await page.waitForTimeout(300);
    await page.screenshot({path: path.join(output, 'rooms-mobile.png')});
    await page.getByRole('button', {name: /^101/}).click();
    await page.getByRole('checkbox', {name: 'Cần dọn', exact: true}).click();
    await page.getByRole('button', {name: 'Lưu', exact: true}).click();
    await page.getByText('Đã lưu', {exact: true}).last().waitFor();
    const updated = await (await fetch(base + `rooms/${original.id}/`, {headers})).json();
    assert.equal(updated.condition, 'cleaning');
    await page.getByRole('tab', {name: 'Thêm', exact: true}).click();
    await page.getByRole('button', {name: /Khách hàng/}).click();
    await page.getByRole('button', {name: new RegExp(guest.full_name)}).waitFor();
    await page.screenshot({path: path.join(output, 'customers-mobile.png')});
    await page.getByRole('button', {name: new RegExp(guest.full_name)}).click();
    const noteInput = page.getByRole('textbox', {name: /Ghi chú/});
    await noteInput.click();
    await noteInput.press('ControlOrMeta+A');
    await noteInput.pressSequentially('Đã kiểm tra luồng lưu trên giao diện.', {delay: 5});
    const submittedGuest = page.waitForRequest(request => request.method() === 'PATCH' && request.url() === base + `customers/${guest.id}/`);
    await page.getByRole('button', {name: 'Lưu', exact: true}).click();
    assert.equal(JSON.parse((await submittedGuest).postData()).notes, 'Đã kiểm tra luồng lưu trên giao diện.');
    await page.getByText('Đã lưu', {exact: true}).last().waitFor();
    const saved = await (await fetch(base + `customers/${guest.id}/`, {headers})).json();
    assert.equal(saved.notes, 'Đã kiểm tra luồng lưu trên giao diện.');
    await fetch(base + `rooms/${original.id}/condition/`, {method: 'POST', headers, body: JSON.stringify({condition: 'ready'})});
    await page.getByRole('tab', {name: 'Đặt phòng', exact: true}).click();
    await page.getByRole('button', {name: 'Đặt phòng mới', exact: true}).click();
    await page.getByRole('button', {name: /Chọn khách hàng/}).click();
    await page.getByRole('button', {name: new RegExp(guest.full_name)}).click();
    await page.getByRole('button', {name: 'Tiếp tục', exact: true}).click();
    await page.getByRole('button', {name: /^101/}).click();
    await page.getByRole('button', {name: 'Tiếp tục', exact: true}).click();
    const bookingResponse = page.waitForResponse(response => response.request().method() === 'POST' && response.url() === base + 'bookings/');
    await page.getByRole('button', {name: 'Đặt phòng', exact: true}).click();
    const booked = await bookingResponse;
    assert.equal(booked.status(), 201);
    createdBooking = await booked.json();
    assert.equal(createdBooking.customer.id, guest.id);
    assert.equal(createdBooking.room.id, original.id);
    await page.getByText(`Đã đặt phòng ${original.number}.`, {exact: true}).last().waitFor();
    await page.screenshot({path: path.join(output, 'bookings-mobile.png')});
    await page.getByRole('button', {name: new RegExp(`101.*${guest.full_name}`)}).click();
    await page.getByRole('button', {name: 'Thao tác khác', exact: true}).click();
    await page.getByRole('menuitem', {name: 'Hủy đặt phòng', exact: true}).or(page.getByRole('button', {name: 'Hủy đặt phòng', exact: true})).first().click();
    await page.getByRole('button', {name: 'Hủy đặt phòng', exact: true}).last().click();
    await page.getByText('Đã cập nhật', {exact: true}).last().waitFor();
    const cancelled = await (await fetch(base + `bookings/${createdBooking.id}/`, {headers})).json();
    assert.equal(cancelled.status, 'cancelled');
    await page.getByRole('button', {name: 'Đóng', exact: true}).click();
    await page.reload({waitUntil: 'networkidle'});
    const restoredPlaceholder = page.locator('flt-semantics-placeholder');
    if (await restoredPlaceholder.count()) await restoredPlaceholder.evaluate(element => element.click());
    await page.getByText('Hôm nay', {exact: true}).first().waitFor();
    assert.equal(await page.getByText('Chào mừng trở lại', {exact: true}).count(), 0);
    assert.deepEqual(errors, []);
    passed = true;
    console.log('UI smoke passed: login, dashboard, room update, customer save, booking create/cancel, refresh-session restore.');
  } finally {
    if (!passed && page) {
      const debug = path.join(root, '.artifacts');
      fs.mkdirSync(debug, {recursive: true});
      await page.screenshot({path: path.join(debug, 'preview-failed.png')});
      console.log(JSON.stringify(await page.locator('[role]').evaluateAll(elements => elements.map(element => ({role: element.getAttribute('role'), label: element.getAttribute('aria-label'), text: (element.innerText || '').slice(0, 160)})).slice(-50)), null, 2));
    }
    await fetch(base + `rooms/${original.id}/condition/`, {method: 'POST', headers, body: JSON.stringify({condition: original.condition})});
    if (createdBooking) await fetch(base + `bookings/${createdBooking.id}/cancel/`, {method: 'POST', headers, body: '{}'});
    await fetch(base + `customers/${guest.id}/`, {method: 'PATCH', headers, body: JSON.stringify({notes: guest.notes})});
    await browser.close();
  }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
